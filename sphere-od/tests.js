const fs=require("fs"),src=fs.readFileSync(__dirname+"/index.html","utf8").match(/<script>([\s\S]*?)<\/script>/)[1];
const m={exports:{}};new Function("module",src)(m);const {solve,W}=m.exports,assert=require("assert");
const D={D:169.91,up:0,lo:0.04,L:60,sp:145,w:46,bl:0.5,zc:-30};
const P=o=>solve(o).prog;

assert.equal(P(D),"G01 X162.544 Z-5.291\nG03 X162.544 Z-54.709 R84.945");
assert.equal(+solve(D).De.toFixed(3),163.544);
assert.equal(+solve(D).xs.toFixed(3),162.544);
assert.equal(+solve(D).mean.toFixed(2),169.89);
assert.equal(P({...D,bl:1}),"G01 X161.544 Z-3.703\nG03 X161.544 Z-56.297 R84.945");
assert.equal(P({...D,bl:0}),"G01 X163.544 Z-7.\nG03 X163.544 Z-53. R84.945");
assert.equal(P({...D,bl:""}),P(D));
assert.equal(P({...D,bl:null}),P(D));
assert.equal(P({...D,zc:30}),P(D));
assert.throws(()=>solve({...D,bl:-0.1}),/0 or more/);
assert.throws(()=>solve({...D,bl:10}),/hit the spigot/);
assert.throws(()=>solve({...D,bl:90}),/larger than the sphere/);
assert.throws(()=>solve({...D,w:70}),/longer than the part/);
assert.throws(()=>solve({...D,D:0}),/Sphere/);
assert.equal(P(D).split("\n").length,2);
assert.equal(W(162.54391489749779),"162.544");
const html=fs.readFileSync(__dirname+"/index.html","utf8");
assert(html.includes('id="bl"')&&html.includes('step="0.1"')&&html.includes('min="0"'));
assert(!html.includes("<form")&&!html.includes('id="ch"'));
assert(html.includes("../sphere-chamfer/"));
assert(fs.readFileSync(__dirname+"/sw.js","utf8").includes("od-sphere-v5"));
assert(fs.readFileSync(__dirname+"/../sphere/sw.js","utf8").includes("sphere-v6"));
assert(fs.readFileSync(__dirname+"/../sphere/tests.js","utf8").includes('G01 X120.05 Z0.914\\nG03 X120.05 Z-33.914 R62.5'));
